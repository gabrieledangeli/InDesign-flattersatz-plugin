import {mkdir, readFile, writeFile} from "node:fs/promises"; // Load tools to create folders and read and write files.
import path from "node:path"; // Load tools that work with file paths.
import {fileURLToPath} from "node:url"; // Load the tool that changes a file URL into a path.

const repository = fileURLToPath(new URL("../", import.meta.url)); // Find the main folder of this repository.
const entry = path.join(repository, "indesign/flattersatz/flattersatz.js"); // Find the main InDesign script.
const destination = path.join(repository, "dist/flattersatz.jsx"); // Choose the path for the complete script.
const args = process.argv.slice(2); // Read the command options after the script name.

if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) { // Reject command options that this tool does not support.
	throw new Error("Usage: node tools/build.mjs [--check]"); // Explain how to run this tool.
} // End this block.

async function bundle(filename, stack = []) { // Make one script from a file and its included files.
	if (stack.includes(filename)) { // Check whether this file includes itself through other files.
		throw new Error(`Circular #include: ${path.relative(repository, filename)}`); // Stop when the included files form a loop.
	} // End this block.
	const source = (await readFile(filename, "utf8")).replace(/^\uFEFF/, "").replace(/\r\n?/g, "\n"); // Read the file and use the same line endings on every system.
	const lines = source.split("\n"); // Split the file into separate lines.
	const output = []; // Prepare a list for the completed lines.
	for (const line of lines) { // Read each source line in order.
		const include = line.match(/^\s*#include\s+["']([^"']+)["'];?\s*(?:\/\/.*)?$/); // Find an include line and allow a comment after it.
		if (include) { // Handle a line that loads another source file.
			const dependency = path.resolve(path.dirname(filename), include[1]); // Find the included file beside the current file.
			const relative = path.relative(repository, dependency); // Find the included file path inside the repository.
			if (relative.startsWith(`..${path.sep}`) || relative === ".." || path.isAbsolute(relative)) { // Reject an include that leaves the repository.
				throw new Error(`Include outside repository: ${include[1]}`); // Stop before reading a file outside the repository.
			} // End this block.
			output.push(await bundle(dependency, [...stack, filename])); // Add the included file after loading its own includes.
		} else { // Handle the other case.
			output.push(line); // Keep a normal source line unchanged.
		} // End this block.
	} // End this block.
	return output.join("\n"); // Join the finished lines into one script.
} // End this block.

const output = "// Generated by npm run build. Edit the sources in indesign/flattersatz/.\n" + await bundle(entry); // Add a note and build the complete InDesign script.

if (args[0] === "--check") { // Check the existing script when the check option is used.
	let existing; // Prepare a place to store the existing script.
	try { // Start work that may report an error.
		existing = await readFile(destination, "utf8"); // Read the script that was built earlier.
	} catch (error) { // Handle an error from the preceding work.
		if (error.code !== "ENOENT") { // Handle errors other than a missing file.
			throw error; // Report the original file error.
		} // End this block.
		throw new Error("Missing dist/flattersatz.jsx. Run npm run build first."); // Ask the user to build the missing script first.
	} // End this block.
	if (existing !== output) { // Compare the built script with the current source files.
		throw new Error("dist/flattersatz.jsx is outdated. Run npm run build."); // Report that the existing script needs a new build.
	} // End this block.
	console.log("dist/flattersatz.jsx matches the sources."); // Report that the built script matches the sources.
} else { // Handle the other case.
	await mkdir(path.dirname(destination), {recursive: true}); // Create the output folder if it does not exist.
	await writeFile(destination, output, "utf8"); // Save the complete script as a UTF-8 text file.
	console.log("Built dist/flattersatz.jsx."); // Report the path of the new script.
} // End this block.
